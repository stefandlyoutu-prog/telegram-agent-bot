export function tipBlock(stepId) {
  const t = TIPS[stepId];
  if (!t) return "";
  const bullets =
    t.bullets?.length > 0
      ? `<details class="tip-extra"><summary>Детали</summary><ul>${t.bullets.map((b) => `<li>${b}</li>`).join("")}</ul></details>`
      : "";
  return `
    <div class="coach slim">
      <div class="coach-natural">${t.natural}</div>
      ${bullets}
    </div>
  `;
}
