export function pitfallsFor(stepId) {
  return PITFALLS.filter((p) => p.where === stepId);
}

export function pitfallsBlock(stepId) {
  const list = pitfallsFor(stepId);
  if (!list.length) return "";
  return `
    <details class="pitfalls">
      <summary>С чем тут часто ошибаются · сравнение «плохо / правильно»</summary>
      <div class="pitfalls-list">
        ${list
          .map(
            (p) => `
          <article class="pitfall">
            <h4>${p.title}</h4>
            <div class="pitfall-grid">
              <div class="pit bad"><span>Так нельзя</span><p>${p.bad}</p></div>
              <div class="pit good"><span>Так надо</span><p>${p.good}</p></div>
            </div>
            <p class="pit-why"><b>Зачем:</b> ${p.why}</p>
          </article>`
          )
          .join("")}
      </div>
    </details>
  `;
}
